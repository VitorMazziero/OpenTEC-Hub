    private static readonly KlaAnchor[] SerratiaAnchors =
    [
        new(2, 800, 121.84), new(7, 800, 179.91), new(12, 800, 195.83),
        new(2, 500, 58.21), new(7, 500, 96.98), new(12, 500, 140.51),
